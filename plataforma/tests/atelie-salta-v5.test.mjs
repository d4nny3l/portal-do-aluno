import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const read=name=>readFileSync(new URL('../atelie-salta-v2-'+name,import.meta.url),'utf8');
const ctx={window:{},Date};
for(const file of ['fixtures.mjs','grade-mask.mjs','calendar.mjs','matrix.mjs'])vm.runInNewContext(read(file),ctx,{timeout:1500});
const F=ctx.window.SALTA_ATELIE_02;
const makeHost=()=>({innerHTML:'',querySelector:()=>null,querySelectorAll:()=>[],addEventListener(){},removeEventListener(){}});
test('DESIGN-05: chamada coletiva atinge coluna explícita sem seleção prévia',()=>{
 const m=F.mountMatrix(makeHost(),'attendance'),s=m.state.attendance;
 assert.equal(s.lesson,0);
 let batch=m.bulk('attendance',1,'F');
 assert.equal(batch.total,30);assert.equal(batch.changed,30);
 assert.equal(s.lesson,1);
 assert.ok(s.students.every(x=>x.states[0]==='P'&&x.states[1]==='F'));
 s.confirmed=[true,true];
 batch=m.bulk('attendance',0,'F');
 assert.equal(s.lesson,0);assert.equal(batch.changed,30);assert.equal(s.confirmed[0],false);assert.equal(s.confirmed[1],true);
 m.dispose();
});
test('DESIGN-05: chamada preserva FJ/FA, motivos, confirmação de outra aula e ajustes',()=>{
 const m=F.mountMatrix(makeHost(),'attendance'),s=m.state.attendance;
 s.students[0].states[0]='FJ';s.students[0].reasons[0]='Motivo sintético';
 s.students[1].states[0]='FA';s.students[1].reasons[0]='Abono sintético';
 s.confirmed=[true,true];
 const res=m.bulk('attendance',0,'F');
 assert.deepEqual(JSON.parse(JSON.stringify(res)),{changed:28,preserved:2,unchanged:0,total:30});
 assert.equal(s.confirmed[0],false);assert.equal(s.confirmed[1],true);
 assert.equal(s.students[0].reasons[0],'Motivo sintético');
 assert.equal(s.students[1].reasons[0],'Abono sintético');
 m.assignCommon(3,0);assert.equal(s.students[3].states[0],'P');
 const noop=m.bulk('attendance',1,'P');assert.equal(noop.changed,0);assert.equal(s.confirmed[1],true);
 m.dispose();
});
test('DESIGN-05: vistos acionam a coluna imediatamente sem escolher atividade antes',()=>{
 const m=F.mountMatrix(makeHost(),'checks'),s=m.state.checks,copy=s.states.map(row=>[...row]);
 assert.equal(m.state.selectedActivity,null);
 const result=m.bulk('checks',3,'✓');
 assert.equal(result.total,30);assert.equal(m.state.selectedActivity,3);
 for(let i=0;i<30;i++)for(let j=0;j<8;j++)if(j!==3)assert.equal(s.states[i][j],copy[i][j]);
 const now=s.states[0][3];m.assignCommon(0,3);assert.notEqual(s.states[0][3],now);
 const individual=s.states[0][3];m.bulk('checks',4,'×');assert.equal(s.states[0][3],individual);
 m.dispose();
});
test('DESIGN-05: vistos protegem ◷/FJ/FA/Isento e independem do filtro',()=>{
 const m=F.mountMatrix(makeHost(),'checks'),s=m.state.checks;
 for(const [i,x] of ['◷','FJ','FA','Isento'].entries())s.states[i][2]=x;
 s.reasons[1][2]='Justificativa fictícia';
 m.state.query='Estudante 07';
 const result=m.bulk('checks',2,'×');
 assert.equal(result.total,30);assert.equal(result.preserved,4);
 assert.deepEqual(s.states.slice(0,4).map(x=>x[2]),['◷','FJ','FA','Isento']);
 assert.equal(s.reasons[1][2],'Justificativa fictícia');
 assert.ok(m.state.feedback.includes('30 estudantes'));
 m.dispose();
});
